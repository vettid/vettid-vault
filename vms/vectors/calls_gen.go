//go:build vmsvectors

package vectors

import (
	"bytes"
	"crypto/ed25519"
	"errors"
	"time"

	"github.com/vettid/vettid-vault/internal/hpkederand"
	"github.com/vettid/vettid-vault/vms/callwire"
	"github.com/vettid/vettid-vault/vms/suite"
)

// genCalls builds calls.json (VAULT-MESSAGING §10.10; not in §16: generated
// here for the apps to reproduce). Everything goes through vms/callwire,
// the code a vault and the reference client run: the caller device's
// ephemeral KEM key, the answering device's encapsulation and k_call, the
// device-signed and vault-vouched shares of both roles, and the vault-signed
// ICE configuration (with servers, and the empty list a vault without a
// calling service signs).
func genCalls() (obj, error) {
	ed := func(seed byte) ed25519.PrivateKey { return ed25519.NewKeyFromSeed(rep(seed, 32)) }
	pub := func(k ed25519.PrivateKey) ed25519.PublicKey { return k.Public().(ed25519.PublicKey) }
	callerDev, callerVault := ed(SeedCallCallerDeviceIK), ed(SeedCallCallerVaultIK)
	calleeDev, calleeVault := ed(SeedCallCalleeDeviceIK), ed(SeedCallCalleeVaultIK)

	// The caller's device: a fresh ephemeral KEM key (call.start `ek`).
	var sk *suite.PrivateKey
	if err := with(newScript(rep(SeedCallOfferKEM, suite.SeedSize)), func() (err error) {
		sk, err = callwire.NewOfferKey()
		return err
	}); err != nil {
		return nil, err
	}
	ek := sk.Public().Bytes()

	// The answering device: enc and k_call (call.answer `enc`).
	var enc, kCall []byte
	if err := with(newScript(rep(RandCallAnswer, hpkederand.RandomnessSize)), func() (err error) {
		enc, kCall, err = callwire.Answer(ek, CallID)
		return err
	}); err != nil {
		return nil, err
	}
	// The exporter secret K, read on the recipient's side (callwire wipes
	// its own copy), and the caller's k_call.
	r, err := suite.SetupRecipient(enc, sk, callwire.LabelCall+CallID)
	if err != nil {
		return nil, err
	}
	k, err := r.Export(callwire.LabelCallKey, callwire.KeySize)
	if err != nil {
		return nil, err
	}
	accepted, err := callwire.Accept(sk, enc, CallID)
	if err != nil {
		return nil, err
	}
	if !bytes.Equal(accepted, kCall) {
		return nil, errors.New("vectors: the two devices derive different call keys")
	}

	// share signs a share as its device and vouches for it as its vault.
	share := func(role, media string, value []byte, dev, vault ed25519.PrivateKey) (obj, error) {
		m := callwire.ShareMessage(role, CallID, media, value)
		ds, err := callwire.SignShare(dev, m)
		if err != nil {
			return nil, err
		}
		vm := callwire.VouchMessage(pub(dev), m)
		vs, err := suite.Sign(vault, callwire.LabelVouch, vm)
		if err != nil {
			return nil, err
		}
		if !callwire.ValidShareMessage(m) || callwire.VerifyDeviceShare(pub(dev), m, ds) != nil ||
			callwire.VerifyShare(pub(vault), pub(dev), m, ds, vs) != nil {
			return nil, errors.New("vectors: a call share does not verify")
		}
		return obj{{"role", role}, {"media", media}, {"message_b64", b64(m)}, {"device_sig_b64", b64(ds)},
			{"vouch_message_b64", b64(vm)}, {"vault_sig_b64", b64(vs)}}, nil
	}
	offer, err := share(callwire.RoleOffer, CallMedia, ek, callerDev, callerVault)
	if err != nil {
		return nil, err
	}
	answer, err := share(callwire.RoleAnswer, "", enc, calleeDev, calleeVault)
	if err != nil {
		return nil, err
	}

	// ICE configurations, signed by the caller's vault for its own device.
	ice := func(servers []callwire.ICEServer) (obj, error) {
		c := &callwire.ICEConfig{CallID: CallID, Exp: time.Unix(CallICEExp, 0).UTC(), Servers: servers}
		cfg, err := c.Marshal()
		if err != nil {
			return nil, err
		}
		sig, err := callwire.SignICE(callerVault, cfg)
		if err != nil {
			return nil, err
		}
		if _, err := callwire.VerifyICE(pub(callerVault), cfg, sig, CallID, time.Unix(CallICEExp-1, 0)); err != nil {
			return nil, err
		}
		return obj{{"config", string(cfg)}, {"ice_config_b64", b64(cfg)}, {"ice_sig_b64", b64(sig)}}, nil
	}
	iceServers, err := ice([]callwire.ICEServer{
		{URLs: []string{"stun:turn.example.org:3478"}},
		{URLs: []string{"turn:turn.example.org:3478?transport=udp", "turns:turn.example.org:443?transport=tcp"},
			Username: "1800000000:" + CallID, Credential: "c2VjcmV0"},
	})
	if err != nil {
		return nil, err
	}
	iceEmpty, err := ice(nil)
	if err != nil {
		return nil, err
	}

	party := func(devSeed, vaultSeed byte, dev, vault ed25519.PrivateKey) obj {
		return obj{{"device_ik_seed_hex", hx(rep(devSeed, 32))}, {"device_ik_b64", b64(pub(dev))},
			{"vault_ik_seed_hex", hx(rep(vaultSeed, 32))}, {"vault_ik_b64", b64(pub(vault))}}
	}
	return obj{
		{"description", "VAULT-MESSAGING §10.10 calls (vms/callwire): not printed in §16; generated by vettid-vault for the apps to reproduce. All keys are TEST ONLY. Key agreement: (enc, ctx) = SetupBaseS(ek, info = label_call || call_id) with MLKEM768X25519 (suite 2, as hpke.json), K = ctx.Export(label_call_key, 32), k_call = HKDF-SHA-256(ikm = K, salt = media_salt, info = call_id, L = 32). Shares: message = role || 0x00 || call_id || 0x00 || media || 0x00 || share (offer: share = ek, media audio or video; answer: share = enc, media empty); device_sig = Ed25519(device ik, label_share || message); vault_sig = Ed25519(vault ik, label_vouch || device_ik || message), the vault being the signing device's own. ICE: ice_sig = Ed25519(vault ik, label_ice || config), config the exact canonical bytes; valid while now < exp and for call_id only. Ed25519 is deterministic (RFC 8032), so every signature here is reproducible."},
		{"label_call", callwire.LabelCall},
		{"label_call_key", callwire.LabelCallKey},
		{"media_salt", callwire.MediaSalt},
		{"label_share", callwire.LabelShare},
		{"label_vouch", callwire.LabelVouch},
		{"label_ice", callwire.LabelICE},
		{"call_id", CallID},
		{"caller", party(SeedCallCallerDeviceIK, SeedCallCallerVaultIK, callerDev, callerVault)},
		{"callee", party(SeedCallCalleeDeviceIK, SeedCallCalleeVaultIK, calleeDev, calleeVault)},
		{"offer_kem_seed_hex", hx(rep(SeedCallOfferKEM, suite.SeedSize))},
		{"ek_b64", b64(ek)},
		{"answer_randomness_hex", hx(rep(RandCallAnswer, hpkederand.RandomnessSize))},
		{"info", callwire.LabelCall + CallID},
		{"enc_b64", b64(enc)},
		{"exporter_hex", hx(k)},
		{"k_call_hex", hx(kCall)},
		{"offer_share", offer},
		{"answer_share", answer},
		{"ice_exp", CallICEExp},
		{"ice", iceServers},
		{"ice_no_servers", iceEmpty},
	}, nil
}
