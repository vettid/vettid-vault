//go:build vmsvectors

package vectors

import (
	"crypto/ed25519"
	"errors"

	"github.com/vettid/vettid-vault/vms/credwire"
	"github.com/vettid/vettid-vault/vms/envelope"
	"github.com/vettid/vettid-vault/vms/peerwire"
)

// genConnAuth builds connauth.json (VAULT-MESSAGING §10.4; not in §16:
// generated here for connection peers to reproduce). Everything goes
// through vms/peerwire, the code a vault and a connection peer run: the
// challenge (its nonce drawn from scripted randomness), the response
// signed with the member's credential key after one rotation (carrying the
// statement from the key the challenger pinned), the refusal, and the
// rotated message.
func genConnAuth() (obj, error) {
	ed := func(seed byte) ed25519.PrivateKey { return ed25519.NewKeyFromSeed(rep(seed, 32)) }
	pub := func(k ed25519.PrivateKey) ed25519.PublicKey { return k.Public().(ed25519.PublicKey) }
	challenger, responder := ed(SeedConnAuthChallengerIK), ed(SeedConnAuthResponderIK)
	credOld, credNew := ed(SeedConnAuthCredOld), ed(SeedConnAuthCredNew)

	var c *peerwire.ConnAuthChallenge
	if err := with(newScript(rep(NonceConnAuth, peerwire.ConnAuthNonceSize)), func() (err error) {
		c, err = peerwire.NewConnAuthChallenge(ConnAuthRequestID, ConnAuthContext)
		return err
	}); err != nil {
		return nil, err
	}
	rot, err := credwire.NewKeyRotation(credOld, credNew)
	if err != nil {
		return nil, err
	}
	signedAt, err := envelope.ParseTS(TS)
	if err != nil {
		return nil, err
	}
	rotations := []*credwire.KeyRotation{rot}
	r, err := peerwire.SignConnAuth(credNew, pub(challenger), pub(responder), c, signedAt, rotations)
	if err != nil {
		return nil, err
	}
	if peerwire.VerifyConnAuthResponse(r, pub(challenger), pub(responder), c) != nil ||
		peerwire.PinnedKeyChanged(pub(credOld), r.Key, r.Rotations) {
		return nil, errors.New("vectors: the conn-auth response does not verify")
	}
	plain, err := peerwire.SignConnAuth(credNew, pub(challenger), pub(responder), c, signedAt, nil)
	if err != nil {
		return nil, err
	}

	key := func(seed byte, k ed25519.PrivateKey) obj {
		return obj{{"seed_hex", hx(rep(seed, 32))}, {"pk_b64", b64(pub(k))}}
	}
	return obj{
		{"description", "VAULT-MESSAGING §10.4 member authentication between connections (vms/peerwire): not printed in §16; generated by vettid-vault for connection peers to reproduce. All keys are TEST ONLY. message = challenger_ik (32) || responder_ik (32) || nonce (32) || request_id (26, ASCII) || context (UTF-8, may be empty); sig = Ed25519(credential key, label || message), deterministic (RFC 8032). The response names the signing credential key; rotations (optional) is the chain of credential-rotate statements (vms/credwire) from the key the challenger pinned (credential_old) to it (credential_new). Bodies are the exact bytes the vault sends."},
		{"label", peerwire.ConnAuthLabel},
		{"challenger_ik", key(SeedConnAuthChallengerIK, challenger)},
		{"responder_ik", key(SeedConnAuthResponderIK, responder)},
		{"credential_old", key(SeedConnAuthCredOld, credOld)},
		{"credential_new", key(SeedConnAuthCredNew, credNew)},
		{"request_id", c.RequestID},
		{"nonce_hex", hx(c.Nonce)},
		{"context", c.Context},
		{"message_hex", hx(c.Message(pub(challenger), pub(responder)))},
		{"sig_b64", b64(r.Sig)},
		{"signed_at", TS},
		{"challenge_body", string(c.Marshal())},
		{"response_body", string(plain.Marshal())},
		{"response_rotated_body", string(r.Marshal())},
		{"denied_body", string(peerwire.DeniedConnAuth(c.RequestID).Marshal())},
		{"rotated_body", string(peerwire.ConnAuthRotatedBody(rotations))},
	}, nil
}
