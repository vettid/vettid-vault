//go:build vmsvectors

package vectors

import (
	"crypto/ed25519"
	"errors"

	"github.com/vettid/vettid-vault/vms/envelope"
	"github.com/vettid/vettid-vault/vms/peerwire"
)

// genConnAuthPurpose builds connauth_purpose.json (VAULT-MESSAGING 0.65.0
// §10.4 "Signed with the purpose"; generated here for connection peers to
// reproduce): the connauth.json challenge with each purpose, the response
// signed over len(purpose) || purpose || message under the purpose label,
// and the response of a vault before 0.65.0, which ignores the purpose and
// signs the message alone under the plain label.
func genConnAuthPurpose() (obj, error) {
	ed := func(seed byte) ed25519.PrivateKey { return ed25519.NewKeyFromSeed(rep(seed, 32)) }
	pub := func(k ed25519.PrivateKey) ed25519.PublicKey { return k.Public().(ed25519.PublicKey) }
	challenger, responder, cred := ed(SeedConnAuthChallengerIK), ed(SeedConnAuthResponderIK), ed(SeedConnAuthCredNew)
	signedAt, err := envelope.ParseTS(TS)
	if err != nil {
		return nil, err
	}
	var c *peerwire.ConnAuthChallenge
	if err := with(newScript(rep(NonceConnAuth, peerwire.ConnAuthNonceSize)), func() (err error) {
		c, err = peerwire.NewConnAuthChallenge(ConnAuthRequestID, ConnAuthContext)
		return err
	}); err != nil {
		return nil, err
	}
	out := obj{
		{"description", "VAULT-MESSAGING 0.65.0 §10.4 \"Signed with the purpose\" (vms/peerwire): not printed in §16; generated by vettid-vault for connection peers to reproduce. Keys, request_id, nonce and context are connauth.json's (TEST ONLY); the signing key is credential_new. For a challenge with purpose \"signin\" or \"approval\": message_purpose = len(purpose) (1 byte) || purpose (UTF-8) || message (connauth.json's message_hex); sig = Ed25519(credential key, label_purpose || message_purpose); the signed response echoes purpose. legacy_response_body is the answer of a vault before 0.65.0 to the signin challenge: no purpose, signed over message alone under connauth.json's label; it verifies, committing to no purpose. Bodies are the exact bytes the vault sends."},
		{"label_purpose", peerwire.ConnAuthPurposeLabel},
	}
	for _, p := range []string{peerwire.PurposeSignIn, peerwire.PurposeApproval} {
		pc := *c
		pc.Purpose = p
		r, err := peerwire.SignConnAuth(cred, pub(challenger), pub(responder), &pc, signedAt, nil)
		if err != nil {
			return nil, err
		}
		if peerwire.VerifyConnAuthResponse(r, pub(challenger), pub(responder), &pc) != nil || r.Purpose != p {
			return nil, errors.New("vectors: the conn-auth purpose response does not verify")
		}
		_, m := pc.Signed(pub(challenger), pub(responder))
		out = append(out, member{p, obj{
			{"challenge_body", string(pc.Marshal())},
			{"message_purpose_hex", hx(m)},
			{"sig_b64", b64(r.Sig)},
			{"response_body", string(r.Marshal())},
		}})
	}
	plain := *c
	legacy, err := peerwire.SignConnAuth(cred, pub(challenger), pub(responder), &plain, signedAt, nil)
	if err != nil {
		return nil, err
	}
	out = append(out, member{"legacy_response_body", string(legacy.Marshal())})
	return out, nil
}
