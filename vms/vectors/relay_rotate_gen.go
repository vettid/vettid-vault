//go:build vmsvectors

package vectors

import (
	"crypto/ed25519"

	"github.com/vettid/vettid-vault/vms/handshake"
)

// Seed bytes of the relay-link vectors: key i is NewKeyFromSeed(32 x
// (SeedRelayLinkBase + i)).
const SeedRelayLinkBase byte = 0xb0

func relayLinkKey(i int) ed25519.PrivateKey {
	return ed25519.NewKeyFromSeed(rep(SeedRelayLinkBase+byte(i), 32))
}

// relayLinkCase is one case: a chain linking the keys in order, changed by
// mutate when given.
func relayLinkCase(name, why string, valid bool, keys []int, mutate func([]*handshake.RelayLink) []*handshake.RelayLink) (obj, error) {
	var links []*handshake.RelayLink
	var linkObjs []any
	var signed []any
	for i := 1; i < len(keys); i++ {
		l, err := handshake.NewRelayLink(relayLinkKey(keys[i-1]), relayLinkKey(keys[i]))
		if err != nil {
			return nil, err
		}
		links = append(links, l)
	}
	if mutate != nil {
		links = mutate(links)
	}
	for _, l := range links {
		linkObjs = append(linkObjs, obj{{"old", b64(l.Old)}, {"new", b64(l.New)}, {"sig_old", b64(l.SigOld)}, {"sig_new", b64(l.SigNew)}})
		signed = append(signed, hx(handshake.RelayLinkSigned(l.Old, l.New)))
	}
	first := relayLinkKey(keys[0]).Public().(ed25519.PublicKey)
	last := links[len(links)-1].New
	return obj{
		{"name", name},
		{"description", why},
		{"first_b64", b64(first)},
		{"announced_b64", b64(last)},
		{"signed_bytes_hex", signed},
		{"links", linkObjs},
		{"valid", valid},
	}, nil
}

// genRelayRotate builds relay_rotate.json: signed relay links (VAULT-
// MESSAGING §3.4.1 rule U, §6.2 relay_links), through vms/handshake.
func genRelayRotate() (obj, error) {
	var keys []any
	for i := 0; i <= 34; i++ {
		k := relayLinkKey(i)
		keys = append(keys, obj{{"index", i}, {"seed_hex", hx(rep(SeedRelayLinkBase+byte(i), 32))}, {"pk_b64", b64(k.Public().(ed25519.PublicKey))}})
	}
	long := make([]int, 34) // 33 links
	for i := range long {
		long[i] = i
	}
	var cases []any
	for _, c := range []struct {
		name, why string
		valid     bool
		keys      []int
		mutate    func([]*handshake.RelayLink) []*handshake.RelayLink
	}{
		{"single", "one link, key 0 -> key 1", true, []int{0, 1}, nil},
		{"chain", "three links, key 0 -> 1 -> 2 -> 3", true, []int{0, 1, 2, 3}, nil},
		{"wrong_signature", "one link whose sig_old has its first byte XOR 0x01", false, []int{0, 1},
			func(ls []*handshake.RelayLink) []*handshake.RelayLink { ls[0].SigOld[0] ^= 1; return ls }},
		{"broken_chain", "key 0 -> 1, then key 2 -> 3: the second link's old is not the first link's new", false, []int{0, 1},
			func(ls []*handshake.RelayLink) []*handshake.RelayLink {
				l, _ := handshake.NewRelayLink(relayLinkKey(2), relayLinkKey(3))
				return append(ls, l)
			}},
		{"too_many", "33 links, key 0 -> 1 -> ... -> 33: one more than the limit of 32", false, long, nil},
	} {
		o, err := relayLinkCase(c.name, c.why, c.valid, c.keys, c.mutate)
		if err != nil {
			return nil, err
		}
		cases = append(cases, o)
	}
	return obj{
		{"description", "VAULT-MESSAGING 0.85.0 §3.4.1 rule U and 0.90.0 §6.2 relay_links: signed relay links. Generated by vettid-vault (vms/handshake) for the apps and service vaults to reproduce. All keys are TEST ONLY: key i is the Ed25519 key of seed 32 x (0xb0 + i). A link is {old, new, sig_old, sig_new}, standard base64 with padding; m = \"vettid/vms/2/relay-rotate\" || old (32) || new (32) (signed_bytes_hex, one per link), sig_old = Ed25519(old, m), sig_new = Ed25519(new, m) (deterministic, RFC 8032). A chain is valid when it has 1 to 32 links, every link's two signatures verify, each link's old is the previous link's new, the first old is first_b64 (the deposit key) and the last new is announced_b64."},
		{"keys", keys},
		{"cases", cases},
	}, nil
}
